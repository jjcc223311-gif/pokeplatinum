# Juniper Johto heads. y -> list of (x, string). '.' clears; unlisted pixels stay.
def mir(rows):
    out = {}
    for y, pieces in rows.items():
        out[y] = [(x, s) for x, s in pieces] + [(31 - x - len(s) + 1, s[::-1]) for x, s in pieces]
    return out
def merge(*ds):
    out = {}
    for d in ds:
        for y, p in d.items(): out.setdefault(y, []).extend(p)
    return out
