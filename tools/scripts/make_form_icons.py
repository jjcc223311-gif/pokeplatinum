#!/usr/bin/env python3
"""Party icons for every appended form: Megas / Legendary Megas (res/pokemon/mega_forms.json) and the
extra forms (res/pokemon/extra_forms.json: Light Arceus, Origin Dialga / Palkia, Kyurem, Gen 5 forms).

Each icon is the form's front sprite (with its normal.pal) shrunk onto the shared icon palettes, like
the Gen 5 placeholder icons (import_gen5_species.make_icon). Writes:
  res/pokemon/<form dir>/icon.png
  res/pokemon/form_icons.txt            form dirs in pl_poke_icon order (read by res/pokemon/meson.build)
  include/data/form_icons.h             sFormIcons[]: species, form, icon palette, same order
usage: make_form_icons.py   (run with a Python that has Pillow + openpyxl)
"""
import json
import sys
import tempfile
from pathlib import Path

from PIL import Image

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT / 'tools' / 'scripts'))
from import_gen5_species import make_icon  # noqa: E402

POKEMON = ROOT / 'res' / 'pokemon'
MEGA_FORMS = {'mega_1': 'FORM_MEGA_1', 'mega_2': 'FORM_MEGA_2',
              'legendary_mega_1': 'FORM_LEGENDARY_MEGA_1', 'legendary_mega_2': 'FORM_LEGENDARY_MEGA_2'}


def read_pal(path):
    vals = [int(v) for v in path.read_text().split()[3:3 + 48]]
    return vals


def main():
    forms = []
    for row in json.loads((POKEMON / 'mega_forms.json').read_text()):
        for key, form in MEGA_FORMS.items():
            if key in row:
                forms.append((row['species'], form, row[key]))
    for row in json.loads((POKEMON / 'extra_forms.json').read_text()):
        forms.append((row['species'], str(row['form']), row['dir']))

    rows = []
    with tempfile.TemporaryDirectory() as tmp:
        for species, form, d in forms:
            src = Image.open(POKEMON / d / 'front.png')
            sheet = src.copy()
            sheet.putpalette(read_pal(POKEMON / d / 'normal.pal') + [0] * (768 - 48))
            tmp_png = Path(tmp) / 'front.png'
            sheet.save(tmp_png)
            palette = make_icon(tmp_png, POKEMON / d / 'icon.png')
            rows.append((species, form, palette, d))

    (POKEMON / 'form_icons.txt').write_text(''.join(f'{d}\n' for *_, d in rows))
    lines = [
        '#ifndef POKEPLATINUM_DATA_FORM_ICONS_H',
        '#define POKEPLATINUM_DATA_FORM_ICONS_H',
        '',
        '// Generated by tools/scripts/make_form_icons.py. Party icons of the appended forms, in the order',
        '// they follow ICON_ROTOM_MOW in pl_poke_icon (res/pokemon/form_icons.txt).',
        '',
        'typedef struct FormIcon {',
        '    u16 species;',
        '    u8 form;',
        '    u8 palette;',
        '} FormIcon;',
        '',
        'static const FormIcon sFormIcons[] = {',
    ]
    lines += [f'    {{ {s}, {f}, {p} }},' for s, f, p, _ in rows]
    lines += ['};', '', '#endif // POKEPLATINUM_DATA_FORM_ICONS_H', '']
    (ROOT / 'include' / 'data' / 'form_icons.h').write_text('\n'.join(lines))
    print(f'{len(rows)} form icons')


if __name__ == '__main__':
    main()
